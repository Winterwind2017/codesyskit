def render(token, port, state_file, log_file, allow_exec=False):
    """Return the IronPython server source with the deployment values baked in."""
    if not token or len(token) < 16:
        raise ValueError("token must be at least 16 characters")
    text = TEMPLATE
    text = text.replace("@@TOKEN@@", token)
    text = text.replace("@@PORT@@", str(int(port)))
    text = text.replace("@@STATE_FILE@@", str(state_file).replace("\\", "\\\\"))
    text = text.replace("@@LOG_FILE@@", str(log_file).replace("\\", "\\\\"))
    text = text.replace("@@ALLOW_EXEC@@", "True" if allow_exec else "False")
    return text
