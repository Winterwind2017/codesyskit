def serve():
    listener = Socket(AddressFamily.InterNetwork, SocketType.Stream, ProtocolType.Tcp)
    listener.SetSocketOption(__import__("System.Net.Sockets", fromlist=["SocketOptionLevel"]).SocketOptionLevel.Socket,
                             __import__("System.Net.Sockets", fromlist=["SocketOptionName"]).SocketOptionName.ReuseAddress,
                             1)
    listener.Bind(IPEndPoint(IPAddress.Loopback, PORT))
    listener.Listen(8)
    actual_port = int(listener.LocalEndPoint.Port)
    write_state(actual_port)
    log("listening on 127.0.0.1:%d (protocol %d)" % (actual_port, PROTOCOL_VERSION))

    buffer = Array.CreateInstance(Byte, 65536)
    running = True
    while running:
        client = listener.Accept()
        pending = ""
        try:
            # One request per connection: the engine is single threaded, and a keep-alive
            # connection would let one client lock everyone else out of the accept loop.
            # Bytes are accumulated and decoded as UTF-8 so non-ASCII text survives.
            while True:
                raw = ""
                while "\n" not in raw:
                    count = client.Receive(buffer)
                    if count <= 0:
                        break
                    raw += "".join([chr(buffer[i]) for i in range(count)])
                if "\n" not in raw:
                    break
                line = raw.split("\n", 1)[0].decode("utf-8", "replace")
                if line.strip():
                    payload, should_quit = handle_line(line)
                    reply(client, payload)
                    if should_quit:
                        running = False
                break
        except Exception as exc:
            log("connection error: %s" % exc)
        finally:
            try:
                client.Close()
            except Exception:
                pass
    try:
        listener.Close()
    except Exception:
        pass
    log("service stopping")
    SYSTEM.exit(0)


