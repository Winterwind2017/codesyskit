def cmd_project_create(args):
    path = args.get("path")
    if not path:
        raise CmdError("E_ARGS", "project.create needs 'path'")
    folder = os.path.dirname(path)
    if folder and not os.path.isdir(folder):
        os.makedirs(folder)
    previous = PROJECTS.primary
    closed_previous = False
    if previous is not None:
        try:
            previous.close()
            closed_previous = True
        except Exception:
            pass
    if os.path.exists(path):
        os.remove(path)
    project = PROJECTS.create(path)
    device_name = args.get("device")
    result = {"path": str(project.path), "closed_previous": closed_previous}
    if device_name:
        picked = None
        for device in list(REPOSITORY.get_all_devices()):
            info = device.device_info
            if str(info.name) == device_name or str(device.device_id) == device_name:
                picked = device
                break
        if picked is None:
            raise CmdError("E_ARGS", "device %r not found in the repository" % device_name)
        project.add(args.get("device_node") or "PLC", picked.device_id)
        result["device"] = str(picked.device_info.name)
        result["device_id"] = str(picked.device_id)
        # A project with no task configuration compiles nothing and reports 0 errors, so a
        # device-only project is a trap; build the minimal skeleton unless asked not to.
        if not args.get("bare"):
            application = project.active_application
            program_name = args.get("program") or "PLC_PRG"
            program = application.create_program(program_name, language=language_guid("st"))
            result["program"] = path_of(program, project)
            result["language"] = "st"
            task = ensure_task(application, args.get("task") or "MainTask",
                               interval=str(args.get("interval") or "20"),
                               unit=args.get("unit") or "ms",
                               priority=str(args.get("priority") or "1"),
                               pous=[program_name])
            result["task"] = name_of(task)
    return result


