"""Generate the IronPython 2.7 server that runs *inside* the CODESYS process.

The generated file is standalone: token, port, state file and log file are baked in as
literals, so the engine needs nothing from the host except this one script.

Design notes that come straight from measurement (see docs/ARCHITECTURE.md):

* ``print()`` in ``--noUI`` mode lands in the IDE message list, so the server never prints;
  it writes a log file and the JSON replies instead.
* ``Socket.Accept()`` returns a single ``Socket`` on IronPython (not a ``(socket, endpoint)``
  tuple), and byte buffers are ``Array.CreateInstance(Byte, n)``.
* the script must call ``system.exit(0)`` itself, otherwise the process stays alive forever.
* commands are serialized: the script engine is single threaded, so the service is a queue of
  one.  Long commands block later ones; callers use ``timeout_ms`` to bound that.
"""

TEMPLATE = r'''# -*- coding: utf-8 -*-
# CODESYS resident service -- generated by codesyskit; do not edit the installed copy.
import codecs
import json
import os
import sys
import time
import traceback

TOKEN = "@@TOKEN@@"
PORT = @@PORT@@
STATE_FILE = "@@STATE_FILE@@"
LOG_FILE = "@@LOG_FILE@@"
ALLOW_EXEC = @@ALLOW_EXEC@@
PROTOCOL_VERSION = 1
DEFAULT_TIMEOUT_MS = 30000
MESSAGE_CATEGORY = "{194B48A9-AB51-43ae-B9A9-51D3EDAADDF3}"

import scriptengine
from System import Array, Byte, Guid
from System.Net import IPAddress, IPEndPoint
from System.Net.Sockets import Socket, SocketType, ProtocolType, AddressFamily

SYSTEM = scriptengine.system
PROJECTS = scriptengine.projects
REPOSITORY = scriptengine.device_repository
STARTED = time.time()


# ---------------------------------------------------------------- infrastructure
class CmdError(Exception):
    def __init__(self, code, message, detail=None):
        Exception.__init__(self, message)
        self.code = code
        self.message = message
        self.detail = detail


def log(text):
    try:
        handle = codecs.open(LOG_FILE, "a", "utf-8")
        try:
            handle.write("%s %s\n" % (time.strftime("%H:%M:%S"), text))
        finally:
            handle.close()
    except Exception:
        pass


def json_dump(value):
    return json.dumps(value, ensure_ascii=False)


def reply(sock, payload):
    text = payload if payload.endswith("\n") else payload + "\n"
    data = Array.CreateInstance(Byte, len(text))
    for index in range(len(text)):
        data[index] = ord(text[index])
    sock.Send(data)


def ok(request_id, result, elapsed_ms):
    return json_dump({"v": PROTOCOL_VERSION, "id": request_id, "ok": True, "code": "OK",
                      "result": result, "elapsed_ms": elapsed_ms})


def failure(request_id, code, message, detail=None, elapsed_ms=0):
    return json_dump({"v": PROTOCOL_VERSION, "id": request_id, "ok": False, "code": code,
                      "error": {"code": code, "message": str(message)[:2000],
                                "detail": None if detail is None else str(detail)[:4000]},
                      "elapsed_ms": elapsed_ms})


# ---------------------------------------------------------------- object helpers
def name_of(obj):
    try:
        return obj.get_name()
    except Exception:
        return None


def path_of(obj, root):
    parts = []
    node = obj
    while node is not None and node is not root:
        parts.insert(0, name_of(node) or "?")
        try:
            node = node.parent
        except Exception:
            node = None
    return "/" + "/".join(parts)


def children(obj):
    try:
        return list(obj.get_children())
    except Exception:
        return []


def primary_project():
    project = PROJECTS.primary
    if project is None:
        raise CmdError("E_STATE", "no project is open")
    return project


def walk(root, path, create=False):
    """Resolve a '/A/B/C' path under ``root``.  Empty path resolves to ``root``."""
    cleaned = (path or "").strip().replace("\\", "/").strip("/")
    node = root
    if not cleaned:
        return node
    for segment in cleaned.split("/"):
        if not segment:
            continue
        found = None
        for child in children(node):
            if name_of(child) == segment:
                found = child
                break
        if found is None:
            if not create:
                raise CmdError("E_STATE", "path segment %r not found under %r"
                               % (segment, path_of(node, root) or "/"))
            found = node.create_folder(segment)
        node = found
    return node


def active_application():
    project = primary_project()
    try:
        application = project.active_application
    except Exception as exc:
        raise CmdError("E_STATE", "no active application (add a device first)", str(exc))
    if application is None:
        raise CmdError("E_STATE", "no active application (add a device first)")
    return project, application


LANGUAGE_NAMES = ("st", "cfc", "page_oriented_cfc", "fbd", "ld", "il", "sfc")


def language_guid(name):
    """Map 'st'/'cfc'/... to the implementation-language Guid, or None for the default."""
    wanted = (name or "st").strip().lower()
    if wanted in ("", "default", "none"):
        return None
    try:
        languages = scriptengine.ImplementationLanguages
    except Exception:
        return None
    try:
        return getattr(languages, wanted)
    except Exception:
        raise CmdError("E_ARGS", "unknown language %r (known: %s)"
                       % (name, ", ".join(LANGUAGE_NAMES)))


def task_configuration(application, create=True):
    for child in children(application):
        try:
            if child.is_task_configuration:
                return child
        except Exception:
            continue
    if not create:
        return None
    return application.create_task_configuration()


def ensure_task(application, name, interval="20", unit="ms", priority="1", pous=None):
    config = task_configuration(application)
    task = None
    for child in children(config):
        if name_of(child) == name:
            task = child
            break
    if task is None:
        task = config.create_task(name)
    for attribute, value in (("interval", interval), ("interval_unit", unit),
                             ("priority", priority)):
        if value is None:
            continue
        try:
            setattr(task, attribute, value)
        except Exception:
            pass
    for pou_name in (pous or []):
        try:
            task.pous.add(pou_name)
        except Exception as exc:
            raise CmdError("E_STATE", "could not map %r to task %r" % (pou_name, name), str(exc))
    return task


def textual(node, part):
    attribute = "textual_declaration" if part == "declaration" else "textual_implementation"
    try:
        document = getattr(node, attribute)
    except Exception as exc:
        raise CmdError("E_ARGS", "%r has no %s" % (name_of(node), part), str(exc))
    if document is None:
        raise CmdError("E_ARGS", "%r has no %s" % (name_of(node), part))
    return document


def write_text(document, text):
    """ScriptTextDocument.text is read-only; replace(offset, length, text) is the way in."""
    document.replace(0, document.length, text)
    return document.text


def message_rows(messages):
    rows = []
    errors = 0
    warnings = 0
    infos = 0
    for message in messages:
        try:
            severity = int(message.severity)
        except Exception:
            severity = 0
        if severity & 3:
            errors += 1
        elif severity & 4:
            warnings += 1
        else:
            infos += 1
        try:
            text = message.text
        except Exception:
            text = str(message)
        row = {"severity": severity, "text": text}
        try:
            row["position"] = message.position_text
        except Exception:
            pass
        rows.append(row)
    return {"errors": errors, "warnings": warnings, "infos": infos,
            "count": len(rows), "items": rows[:200]}


# ---------------------------------------------------------------- commands
def cmd_ping(args):
    return {"protocol": PROTOCOL_VERSION, "banner": sys.version,
            "ui_present": bool(SYSTEM.ui_present), "pid": os.getpid(),
            "uptime_s": round(time.time() - STARTED, 1)}


def cmd_version(args):
    return {"banner": sys.version, "protocol": PROTOCOL_VERSION,
            "executable": str(SYSTEM.executable_filename)}


def cmd_devices(args):
    limit = int(args.get("limit", 20) or 20)
    needle = args.get("filter")
    items = []
    total = 0
    for device in list(REPOSITORY.get_all_devices()):
        total += 1
        info = device.device_info
        name = str(info.name)
        if needle and needle.lower() not in name.lower():
            continue
        if len(items) < limit:
            items.append({"name": name, "vendor": str(info.vendor),
                          "id": str(device.device_id),
                          "default_instance_name": str(getattr(info, "default_instance_name", "") or "")})
    return {"count": total, "returned": len(items), "items": items}


def cmd_projects(args):
    project = PROJECTS.primary
    if project is None:
        return {"primary": None}
    return {"primary": {"path": str(project.path), "name": os.path.basename(str(project.path)),
                        "dirty": bool(project.dirty)}}


def cmd_project_create(args):
    path = args.get("path")
    if not path:
        raise CmdError("E_ARGS", "project.create needs 'path'")
    folder = os.path.dirname(path)
    if folder and not os.path.isdir(folder):
        os.makedirs(folder)
    if os.path.exists(path):
        os.remove(path)
    project = PROJECTS.create(path)
    device_name = args.get("device")
    result = {"path": str(project.path)}
    if device_name:
        picked = None
        for device in list(REPOSITORY.get_all_devices()):
            info = device.device_info
            if str(info.name) == device_name or str(device.device_id) == device_name:
                picked = device
                break
        if picked is None:
            raise CmdError("E_ARGS", "device %r not found in the repository" % device_name)
        project.add(args.get("device_node") or "PLC", picked.device_id)
        result["device"] = str(picked.device_info.name)
        result["device_id"] = str(picked.device_id)
        # A project with no task configuration compiles nothing and reports 0 errors, so a
        # device-only project is a trap; build the minimal skeleton unless asked not to.
        if not args.get("bare"):
            application = project.active_application
            program_name = args.get("program") or "PLC_PRG"
            program = application.create_program(program_name, language=language_guid("st"))
            result["program"] = path_of(program, project)
            result["language"] = "st"
            task = ensure_task(application, args.get("task") or "MainTask",
                               interval=str(args.get("interval") or "20"),
                               unit=args.get("unit") or "ms",
                               priority=str(args.get("priority") or "1"),
                               pous=[program_name])
            result["task"] = name_of(task)
    return result


def cmd_project_open(args):
    path = args.get("path")
    if not path:
        raise CmdError("E_ARGS", "project.open needs 'path'")
    if not os.path.exists(path):
        raise CmdError("E_STATE", "no such project: %s" % path)
    project = PROJECTS.open(path)
    return {"path": str(project.path), "dirty": bool(project.dirty)}


def cmd_project_save(args):
    project = primary_project()
    path = args.get("path")
    if path:
        project.save_as(path)
        return {"path": str(project.path), "saved_as": True}
    project.save()
    return {"path": str(project.path), "dirty": bool(project.dirty)}


def cmd_project_close(args):
    project = primary_project()
    path = str(project.path)
    project.close()
    return {"closed": path}


def cmd_project_info(args):
    project = primary_project()
    info = {"path": str(project.path), "dirty": bool(project.dirty)}
    try:
        application = project.active_application
    except Exception:
        application = None
    if application is not None:
        info["application"] = {"name": name_of(application),
                               "path": path_of(application, project)}
    info["children"] = [{"name": name_of(child), "path": path_of(child, project)}
                        for child in children(project)]
    return info


def cmd_tree(args):
    project = primary_project()
    node = walk(project, args.get("path", ""))
    depth = int(args.get("depth", 2) or 2)

    def collect(item, level):
        rows = []
        for child in children(item):
            rows.append({"name": name_of(child), "path": path_of(child, project),
                         "type": str(child.type) if hasattr(child, "type") else None})
            if level > 1:
                rows.extend(collect(child, level - 1))
        return rows

    return {"path": path_of(node, project) or "/", "items": collect(node, depth)}


def cmd_pou_read(args):
    project = primary_project()
    part = args.get("part") or "declaration"
    if part not in ("declaration", "implementation"):
        raise CmdError("E_ARGS", "part must be declaration|implementation")
    node = walk(project, args.get("path", ""))
    document = textual(node, part)
    return {"path": path_of(node, project), "part": part, "text": document.text,
            "length": document.length, "linecount": document.linecount}


def cmd_pou_write(args):
    project = primary_project()
    part = args.get("part") or "declaration"
    if part not in ("declaration", "implementation"):
        raise CmdError("E_ARGS", "part must be declaration|implementation")
    text = args.get("text")
    if text is None:
        raise CmdError("E_ARGS", "pou.write needs 'text'")
    node = walk(project, args.get("path", ""))
    document = textual(node, part)
    write_text(document, text)
    readback = document.text
    return {"path": path_of(node, project), "part": part, "length": document.length,
            "readback_match": readback == text, "readback": readback}


def cmd_pou_create(args):
    project, application = active_application()
    kind = args.get("kind") or "program"
    name = args.get("name")
    if not name:
        raise CmdError("E_ARGS", "pou.create needs 'name'")
    parent = walk(project, args["parent"]) if args.get("parent") else application
    language = language_guid(args.get("language") or "st")
    if kind == "program":
        created = parent.create_program(name, language=language)
    elif kind == "function_block":
        created = parent.create_function_block(name)
    elif kind == "gvl":
        created = parent.create_gvl(name)
    elif kind == "dut":
        created = parent.create_dut(name)
    else:
        raise CmdError("E_ARGS", "unknown kind %r" % kind)
    return {"path": path_of(created, project), "name": name_of(created), "kind": kind,
            "language": args.get("language") or "st"}


def cmd_task_create(args):
    project, application = active_application()
    name = args.get("name") or "MainTask"
    pous = args.get("pous") or []
    task = ensure_task(application, name,
                       interval=str(args.get("interval") or "20"),
                       unit=args.get("unit") or "ms",
                       priority=str(args.get("priority") or "1"),
                       pous=pous)
    return {"task": name_of(task), "path": path_of(task, project), "pous": pous}


def cmd_tasks(args):
    project, application = active_application()
    config = task_configuration(application, create=False)
    if config is None:
        return {"count": 0, "items": []}
    items = []
    for task in children(config):
        mapped = []
        try:
            mapped = list(task.pous)
        except Exception:
            mapped = []
        items.append({"name": name_of(task), "path": path_of(task, project),
                      "kind": str(task.kind_of_task), "interval": str(task.interval),
                      "pous": [str(entry) for entry in mapped]})
    return {"count": len(items), "items": items}


def cmd_build(args):
    project, application = active_application()
    cleared = False
    try:
        SYSTEM.clear_messages(Guid(MESSAGE_CATEGORY))
        cleared = True
    except Exception:
        cleared = False
    started = time.time()
    application.build()
    elapsed = int((time.time() - started) * 1000)
    try:
        messages = list(SYSTEM.get_messages(MESSAGE_CATEGORY))
    except Exception:
        messages = []
    summary = message_rows(messages)
    summary.update({"ok": summary["errors"] == 0, "cleared": cleared,
                    "build_ms": elapsed, "application": path_of(application, project)})
    return summary


def cmd_messages(args):
    try:
        messages = list(SYSTEM.get_messages(MESSAGE_CATEGORY))
    except Exception:
        messages = []
    summary = message_rows(messages)
    if args.get("clear"):
        try:
            SYSTEM.clear_messages(Guid(MESSAGE_CATEGORY))
        except Exception:
            pass
    return summary


def cmd_batch(args):
    calls = args.get("calls")
    if not isinstance(calls, list) or not calls:
        raise CmdError("E_ARGS", "batch needs a non-empty 'calls' list")
    stop_on_error = bool(args.get("stop_on_error", False))
    results = []
    for index, call in enumerate(calls):
        command = (call or {}).get("cmd")
        call_args = (call or {}).get("args") or {}
        entry = {"index": index, "cmd": command}
        try:
            handler = COMMANDS.get(command)
            if handler is None:
                raise CmdError("E_UNKNOWN_CMD", "unknown command %r" % command)
            entry["ok"] = True
            entry["code"] = "OK"
            entry["result"] = handler(call_args)
        except CmdError as exc:
            entry.update({"ok": False, "code": exc.code,
                          "error": {"code": exc.code, "message": exc.message,
                                    "detail": exc.detail}})
        except Exception as exc:
            entry.update({"ok": False, "code": "E_SCRIPT",
                          "error": {"code": "E_SCRIPT", "message": str(exc)[:500],
                                    "detail": traceback.format_exc()}})
        results.append(entry)
        if stop_on_error and not entry["ok"]:
            break
    return {"results": results, "executed": len(results)}


def cmd_exec(args):
    if not ALLOW_EXEC:
        raise CmdError("E_UNAVAILABLE", "exec is disabled; start the service with allow_exec")
    source = args.get("source")
    if not source:
        raise CmdError("E_ARGS", "exec needs 'source'")
    scope = {"scriptengine": scriptengine, "system": SYSTEM, "projects": PROJECTS,
             "device_repository": REPOSITORY}
    exec(compile(source, "<codesyskit exec>", "exec"), scope)
    return {"executed": True,
            "locals": sorted([key for key in scope.keys() if not key.startswith("__")])}


def cmd_quit(args):
    return {"bye": True}


COMMANDS = {
    "ping": cmd_ping,
    "version": cmd_version,
    "devices": cmd_devices,
    "projects": cmd_projects,
    "project.create": cmd_project_create,
    "project.open": cmd_project_open,
    "project.save": cmd_project_save,
    "project.close": cmd_project_close,
    "project.info": cmd_project_info,
    "tree": cmd_tree,
    "pou.read": cmd_pou_read,
    "pou.write": cmd_pou_write,
    "pou.create": cmd_pou_create,
    "task.create": cmd_task_create,
    "tasks": cmd_tasks,
    "build": cmd_build,
    "messages": cmd_messages,
    "batch": cmd_batch,
    "exec": cmd_exec,
    "quit": cmd_quit,
}


# ---------------------------------------------------------------- request loop
def handle_line(line):
    """Return (payload, should_quit)."""
    started = time.time()
    request_id = None
    try:
        try:
            request = json.loads(line)
        except Exception as exc:
            return failure(None, "E_PROTOCOL", "request is not json", str(exc)), False
        if not isinstance(request, dict):
            return failure(None, "E_PROTOCOL", "request must be an object"), False
        request_id = request.get("id")
        version = request.get("v", PROTOCOL_VERSION)
        if version != PROTOCOL_VERSION:
            return failure(request_id, "E_PROTOCOL", "protocol version %r not supported" % (version,)), False
        if request.get("token") != TOKEN:
            log("token reject from request %r" % (request_id,))
            return failure(request_id, "E_TOKEN", "bad or missing token"), False
        command = request.get("cmd")
        handler = COMMANDS.get(command)
        if handler is None:
            return failure(request_id, "E_UNKNOWN_CMD", "unknown command %r" % (command,)), False
        args = request.get("args") or {}
        if not isinstance(args, dict):
            return failure(request_id, "E_ARGS", "args must be an object"), False
        timeout_ms = int(request.get("timeout_ms") or DEFAULT_TIMEOUT_MS)
        result = handler(args)
        elapsed = int((time.time() - started) * 1000)
        if timeout_ms > 0 and elapsed > timeout_ms:
            return failure(request_id, "E_TIMEOUT",
                           "command %r exceeded %d ms (took %d ms)" % (command, timeout_ms, elapsed),
                           None, elapsed), False
        payload = ok(request_id, result, elapsed)
        return payload, command == "quit"
    except CmdError as exc:
        return failure(request_id, exc.code, exc.message, exc.detail,
                       int((time.time() - started) * 1000)), False
    except Exception as exc:
        return failure(request_id, "E_SCRIPT", str(exc)[:500], traceback.format_exc(),
                       int((time.time() - started) * 1000)), False


def write_state(port):
    try:
        handle = codecs.open(STATE_FILE, "w", "utf-8")
        try:
            handle.write(json_dump({"protocol": PROTOCOL_VERSION, "port": port,
                                    "token": TOKEN, "pid": os.getpid(),
                                    "started": time.time(), "banner": sys.version,
                                    "ui_present": bool(SYSTEM.ui_present)}))
        finally:
            handle.close()
    except Exception as exc:
        log("state file failed: %s" % exc)


def serve():
    listener = Socket(AddressFamily.InterNetwork, SocketType.Stream, ProtocolType.Tcp)
    listener.SetSocketOption(__import__("System.Net.Sockets", fromlist=["SocketOptionLevel"]).SocketOptionLevel.Socket,
                             __import__("System.Net.Sockets", fromlist=["SocketOptionName"]).SocketOptionName.ReuseAddress,
                             1)
    listener.Bind(IPEndPoint(IPAddress.Loopback, PORT))
    listener.Listen(8)
    actual_port = int(listener.LocalEndPoint.Port)
    write_state(actual_port)
    log("listening on 127.0.0.1:%d (protocol %d)" % (actual_port, PROTOCOL_VERSION))

    buffer = Array.CreateInstance(Byte, 65536)
    running = True
    while running:
        client = listener.Accept()
        pending = ""
        try:
            # One request per connection: the engine is single threaded, and a keep-alive
            # connection would let one client lock everyone else out of the accept loop.
            while "\n" not in pending:
                count = client.Receive(buffer)
                if count <= 0:
                    break
                pending += "".join([chr(buffer[i]) for i in range(count)])
            if "\n" in pending:
                line = pending.split("\n", 1)[0]
                if line.strip():
                    payload, should_quit = handle_line(line)
                    reply(client, payload)
                    if should_quit:
                        running = False
        except Exception as exc:
            log("connection error: %s" % exc)
        finally:
            try:
                client.Close()
            except Exception:
                pass
    try:
        listener.Close()
    except Exception:
        pass
    log("service stopping")
    SYSTEM.exit(0)


try:
    serve()
except Exception:
    log("FATAL " + traceback.format_exc())
    try:
        SYSTEM.exit(1)
    except Exception:
        pass
'''


def render(token, port, state_file, log_file, allow_exec=False):
    """Return the IronPython server source with the deployment values baked in."""
    if not token or len(token) < 16:
        raise ValueError("token must be at least 16 characters")
    text = TEMPLATE
    text = text.replace("@@TOKEN@@", token)
    text = text.replace("@@PORT@@", str(int(port)))
    text = text.replace("@@STATE_FILE@@", str(state_file).replace("\\", "\\\\"))
    text = text.replace("@@LOG_FILE@@", str(log_file).replace("\\", "\\\\"))
    text = text.replace("@@ALLOW_EXEC@@", "True" if allow_exec else "False")
    return text
