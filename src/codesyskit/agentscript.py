def cmd_tree(args):
    project = primary_project()
    node = walk(project, args.get("path", ""))
    depth = int(args.get("depth", 2) or 2)

    def collect(item, level):
        rows = []
        for child in children(item):
            rows.append({"name": name_of(child), "path": path_of(child, project),
                         "type": str(child.type) if hasattr(child, "type") else None})
            if level > 1:
                rows.extend(collect(child, level - 1))
        return rows

    return {"path": path_of(node, project) or "/", "items": collect(node, depth)}


