"""Generate the IronPython 2.7 server that runs *inside* the CODESYS process.

The generated file is standalone: token, port, state file and log file are baked in as
literals, so the engine needs nothing from the host except this one script.

Design notes that come straight from measurement (see docs/ARCHITECTURE.md):

* ``print()`` in ``--noUI`` mode lands in the IDE message list, so the server never prints;
  it writes a log file and the JSON replies instead.
* ``Socket.Accept()`` returns a single ``Socket`` on IronPython (not a ``(socket, endpoint)``
  tuple), and byte buffers are ``Array.CreateInstance(Byte, n)``.
* the script must call ``system.exit(0)`` itself, otherwise the process stays alive forever.
* commands are serialized: the script engine is single threaded, so the service is a queue of
  one.  Long commands block later ones; callers use ``timeout_ms`` to bound that.
"""

