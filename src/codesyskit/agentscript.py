# ---------------------------------------------------------------- request loop
def handle_line(line):
    """Return (payload, should_quit)."""
    started = time.time()
    request_id = None
    try:
        try:
            request = json.loads(line)
        except Exception as exc:
            return failure(None, "E_PROTOCOL", "request is not json", str(exc)), False
        if not isinstance(request, dict):
            return failure(None, "E_PROTOCOL", "request must be an object"), False
        request_id = request.get("id")
        version = request.get("v", PROTOCOL_VERSION)
        if version != PROTOCOL_VERSION:
            return failure(request_id, "E_PROTOCOL", "protocol version %r not supported" % (version,)), False
        if request.get("token") != TOKEN:
            log("token reject from request %r" % (request_id,))
            return failure(request_id, "E_TOKEN", "bad or missing token"), False
        command = request.get("cmd")
        handler = COMMANDS.get(command)
        if handler is None:
            return failure(request_id, "E_UNKNOWN_CMD", "unknown command %r" % (command,)), False
        args = request.get("args") or {}
        if not isinstance(args, dict):
            return failure(request_id, "E_ARGS", "args must be an object"), False
        timeout_ms = int(request.get("timeout_ms") or DEFAULT_TIMEOUT_MS)
        result = handler(args)
        elapsed = int((time.time() - started) * 1000)
        if timeout_ms > 0 and elapsed > timeout_ms:
            return failure(request_id, "E_TIMEOUT",
                           "command %r exceeded %d ms (took %d ms)" % (command, timeout_ms, elapsed),
                           None, elapsed), False
        payload = ok(request_id, result, elapsed)
        return payload, command == "quit"
    except CmdError as exc:
        return failure(request_id, exc.code, exc.message, exc.detail,
                       int((time.time() - started) * 1000)), False
    except Exception as exc:
        return failure(request_id, "E_SCRIPT", str(exc)[:500], traceback.format_exc(),
                       int((time.time() - started) * 1000)), False


